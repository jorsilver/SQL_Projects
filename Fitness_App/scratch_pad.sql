DROP PROCEDURE IF EXISTS get_workout_exercises;


DELIMITER $$
CREATE PROCEDURE get_workout_exercises(IN workout_id INT)
BEGIN
    SELECT
        e.exercise_id,
        e.name,
        e.muscle_group,
        e.description,
        JSON_ARRAYAGG(
            JSON_OBJECT(
                'set_number', we.set_number,
                'reps_or_distance', COALESCE(we.reps, we.distance)
            )
        ) AS sets_and_reps
    FROM
        exercise e
    JOIN
        workout_exercise we ON e.exercise_id = we.exercise_id
    WHERE
        we.workout_id = workout_id
    GROUP BY
        e.exercise_id, e.name, e.muscle_group, e.description
    ORDER BY
        e.muscle_group;
END $$
DELIMITER ;


DELIMITER $$
CREATE DEFINER=`root`@`localhost` PROCEDURE `get_active_program_details`(IN program_id INT)
BEGIN
    SELECT
        p.program_id,
        p.program_name,
        p.description,
        p.days_per_week,
        p.focus,
        p.public,
        (
            SELECT JSON_ARRAYAGG(
                JSON_OBJECT(
                    'workout_id', w.workout_id,
                    'workout_name', w.workout_name,
                    'approx_duration', w.approx_duration_mins
                )
            )
            FROM program_workout pw
            JOIN workout w ON pw.workout_id = w.workout_id
            WHERE pw.program_id = p.program_id
        ) AS workouts
    FROM
        program p
    WHERE
        p.program_id = program_id;
END $$
