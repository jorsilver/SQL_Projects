UPDATE workout w
SET approx_duration_mins = (
    SELECT SUM(
        CASE
            WHEN we.reps IS NOT NULL THEN (e.10_reps_time_secs * we.reps / 10) / 60
            WHEN we.distance IS NOT NULL THEN (we.distance * e.10_reps_time_secs * 10) / 60
            ELSE 0
        END
    )
    FROM workout_exercise we
    JOIN exercise e ON we.exercise_id = e.exercise_id
    WHERE we.workout_id = w.workout_id
    AND (we.reps IS NOT NULL OR we.distance IS NOT NULL)
);

